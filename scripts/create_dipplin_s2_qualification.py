class QualificationError(RuntimeError):
    """Qualification is pending or an integrity/rule check failed closed."""


@dataclass(frozen=True)
class QualificationContract:
    root: Path
    output: Path
    stage_report: Path
    s1_validation: Path
    s2_validation: Path
    validation_manifest: Path
    evaluator: Path
    stage_evaluator: Path
    stage_spec: Path
    creator: Path
    pins: Mapping[str, str]
    primary_record_count: int
    validation_episode_count: int
    exploratory_hard_ceiling: int
    validation_parameters: Mapping[str, int]


def _canonical_bytes(value: object) -> bytes:
    return json.dumps(
        value, ensure_ascii=True, sort_keys=True, separators=(",", ":"), default=str
    ).encode("utf-8")


def _object_sha256(value: object) -> str:
    return hashlib.sha256(_canonical_bytes(value)).hexdigest().upper()


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest().upper()


def _git_blob_sha1(path: Path) -> str:
    data = path.read_bytes()
    return hashlib.sha1(
        b"blob " + str(len(data)).encode("ascii") + b"\0" + data
    ).hexdigest().upper()


def _mapping(value: object, field: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        raise QualificationError(f"{field} must be an object")
    return value


def _rows(value: object, field: str) -> list[Mapping[str, Any]]:
    if not isinstance(value, list) or any(not isinstance(row, Mapping) for row in value):
        raise QualificationError(f"{field} must be an array of objects")
    return list(value)


def _integer(value: object, field: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise QualificationError(f"{field} must be an integer")
    return value


def _number(value: object, field: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise QualificationError(f"{field} must be numeric")
    result = float(value)
    if not math.isfinite(result):
        raise QualificationError(f"{field} must be finite")
    return result


def _read_json(path: Path, field: str) -> dict[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise QualificationError(f"invalid {field}: {exc}") from exc
    if not isinstance(payload, dict):
        raise QualificationError(f"{field} must be a JSON object")
    return payload


def _relative(path: Path, root: Path, field: str) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError as exc:
        raise QualificationError(f"{field} escapes the repository") from exc


def _resolve_report_path(raw: object, *, report: Path, root: Path, field: str) -> Path:
    if not isinstance(raw, str) or not raw:
        raise QualificationError(f"{field} path is missing")
    supplied = Path(raw).expanduser()
    candidates = [supplied] if supplied.is_absolute() else [root / supplied, report.parent / supplied]
    path = next((candidate.resolve() for candidate in candidates if candidate.is_file()), None)
    if path is None:
        raise QualificationError(f"{field} source artifact is missing")
    _relative(path, root, field)
    return path


def _provenance(path: Path, root: Path) -> dict[str, str]:
    return {
        "path": _relative(path, root, "provenance"),
        "sha256": _sha256(path),
        "git_blob_sha1": _git_blob_sha1(path),
    }


